const keys = Object.keys(english).sort((a, b) => b.length - a.length);
const escapeRegex = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const pattern = new RegExp(keys.map(escapeRegex).join("|"), "g");
/** Translate explicit game-owned presentation strings, including composite rule messages.
 * Call before inserting a user name; never pass player input, HTML or the DOM here. */
export function t(source: string): string {
  if (locale === "zh-CN") return simplifiedChinese[source] ?? source;
  if (english[source] !== undefined) return english[source];
  for (const [expression, format] of formats) {
    const match = expression.exec(source);
    if (match) return format(...match.slice(1));
  }
  return source.replace(pattern, (key) => english[key] ?? key);
}
/** Only authored localization bindings are visited. Child markup and inputs stay intact. */
