export function chooseLocale(saved: string | null, languages: readonly string[]): Locale {
  if (saved === "en" || saved === "zh-CN") return saved;
  const preferred = languages.find(language => /^(zh|en)(?:-|$)/i.test(language));
  return preferred?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}
let locale: Locale = "en";
export function getLocale(): Locale { return locale; }
export function initializeLocale(): void {
  let saved: string | null = null;
  try { saved = localStorage.getItem(LANGUAGE_KEY); } catch { /* Private mode still works. */ }
  locale = chooseLocale(saved, navigator.languages?.length ? navigator.languages : [navigator.language]);
  document.documentElement.lang = locale;
}
export function setLocale(next: Locale): void {
  if (next !== "en" && next !== "zh-CN") return;
  locale = next;
  try { localStorage.setItem(LANGUAGE_KEY, next); } catch { /* Storage is optional. */ }
  document.documentElement.lang = next;
}
